-- PostgreSQL port of data/schema.sql.
-- SQLite AUTOINCREMENT becomes identity columns. Partial unique indexes stay.

CREATE TABLE IF NOT EXISTS journals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pmid TEXT,
  doi TEXT,
  title TEXT NOT NULL,
  authors TEXT,
  journal_name TEXT,
  year INTEGER,
  volume TEXT,
  issue TEXT,
  pages TEXT,
  abstract TEXT,
  url TEXT,
  source_type TEXT NOT NULL DEFAULT 'file',
  source_path TEXT,
  ingested_at TEXT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_journals_pmid
  ON journals (pmid) WHERE pmid IS NOT NULL AND pmid <> '';

CREATE UNIQUE INDEX IF NOT EXISTS idx_journals_doi
  ON journals (doi) WHERE doi IS NOT NULL AND doi <> '';

CREATE TABLE IF NOT EXISTS medical_data (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  journal_id INTEGER NOT NULL,
  claim TEXT NOT NULL,
  quote TEXT NOT NULL,
  topic TEXT,
  section TEXT,
  population TEXT,
  intervention TEXT,
  outcome TEXT,
  evidence_level TEXT,
  keywords TEXT,
  ingested_at TEXT NOT NULL,
  FOREIGN KEY (journal_id) REFERENCES journals (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_medical_data_quote
  ON medical_data (journal_id, quote);

CREATE INDEX IF NOT EXISTS idx_medical_data_journal ON medical_data (journal_id);
CREATE INDEX IF NOT EXISTS idx_medical_data_topic ON medical_data (topic);
CREATE INDEX IF NOT EXISTS idx_journals_year ON journals (year);

CREATE TABLE IF NOT EXISTS reports (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id TEXT NOT NULL,
  encounter_id TEXT,
  kind TEXT NOT NULL,
  title TEXT NOT NULL,
  filename TEXT NOT NULL,
  stored_name TEXT NOT NULL,
  uploaded_by TEXT NOT NULL,
  uploader_role TEXT,
  size_bytes INTEGER NOT NULL,
  uploaded_at TEXT NOT NULL,
  extracted_text TEXT
);

CREATE INDEX IF NOT EXISTS idx_reports_patient ON reports (patient_id, uploaded_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_reports_stored ON reports (stored_name);

CREATE TABLE IF NOT EXISTS conversations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_key TEXT NOT NULL,
  title TEXT NOT NULL,
  topic TEXT,
  setting TEXT,
  source_type TEXT NOT NULL DEFAULT 'corpus',
  source_path TEXT,
  ingested_at TEXT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_conversations_source_key
  ON conversations (source_key);

CREATE INDEX IF NOT EXISTS idx_conversations_topic ON conversations (topic);

CREATE TABLE IF NOT EXISTS conversation_turns (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id INTEGER NOT NULL,
  turn_index INTEGER NOT NULL,
  speaker TEXT NOT NULL,
  text TEXT NOT NULL,
  move TEXT,
  ingested_at TEXT NOT NULL,
  FOREIGN KEY (conversation_id) REFERENCES conversations (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_conversation_turns_order
  ON conversation_turns (conversation_id, turn_index);

CREATE INDEX IF NOT EXISTS idx_conversation_turns_speaker
  ON conversation_turns (speaker, move);

-- Imported sample panel from pareshbadnore/diagnostic-pathology-test-results.
-- Rows are sample records, not VirtuSP patients.
CREATE TABLE IF NOT EXISTS pathology_results (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source TEXT NOT NULL,
  source_row INTEGER NOT NULL,
  blood_glucose DOUBLE PRECISION,
  hba1c DOUBLE PRECISION,
  systolic_bp DOUBLE PRECISION,
  diastolic_bp DOUBLE PRECISION,
  ldl DOUBLE PRECISION,
  hdl DOUBLE PRECISION,
  triglycerides DOUBLE PRECISION,
  haemoglobin DOUBLE PRECISION,
  mcv DOUBLE PRECISION,
  condition TEXT NOT NULL,
  ingested_at TEXT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_pathology_source_row
  ON pathology_results (source, source_row);

CREATE INDEX IF NOT EXISTS idx_pathology_condition
  ON pathology_results (condition);

CREATE TABLE IF NOT EXISTS pathology_evaluations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id TEXT NOT NULL,
  patient_name TEXT NOT NULL,
  markers_present TEXT NOT NULL,
  markers_unspecified TEXT NOT NULL,
  nearest_condition TEXT,
  distance DOUBLE PRECISION,
  distances TEXT NOT NULL,
  sample_rows INTEGER NOT NULL,
  summary TEXT NOT NULL,
  evaluated_at TEXT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_pathology_eval_patient
  ON pathology_evaluations (patient_id);
